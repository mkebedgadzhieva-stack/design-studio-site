# Индексы точек осевой линии, где начинаются сегменты tail-1…tail-5.
TAIL_BREAKS = [0, 3, 6, 9, 13]
TAIL_HALF_WIDTH = 46  # полуширина полосы сегмента при вырезании (с запасом)


def _tail_strip(i0, i1, base_cut=None):
    """Полигон-полоса вдоль осевой линии хвоста между точками i0..i1."""
    pts = TAIL_AXIS[i0:i1 + 1]
    left, right = [], []
    for k, (x, y) in enumerate(pts):
        a = pts[max(k - 1, 0)]
        b = pts[min(k + 1, len(pts) - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        n = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / n, dx / n
        w = TAIL_HALF_WIDTH
        left.append((x + nx * w, y + ny * w))
        right.append((x - nx * w, y - ny * w))
    if base_cut:
        left[0], right[0] = base_cut
    return left + right[::-1]


def tail_parts():
    parts = []
    n = len(TAIL_AXIS) - 1
    for s, i0 in enumerate(TAIL_BREAKS):
        i1 = TAIL_BREAKS[s + 1] if s + 1 < len(TAIL_BREAKS) else n
        base_cut = ((640, 418), (712, 318)) if s == 0 else None
        if s == len(TAIL_BREAKS) - 1:
            i1 = n
        parts.append({
            "id": f"tail-{s + 1}",
            "parent": "torso-back" if s == 0 else f"tail-{s}",
            "pivot": TAIL_AXIS[i0],
            "core": _tail_strip(i0, i1, base_cut),
            "grow": 20 if s == 0 else 14,
            "cap": s > 0,
            "layer": "back" if s == 0 else "front",
        })
    # Кончик завитка: полоса заканчивается чуть дальше последней точки.
    return parts


